#!/usr/bin/env python3
"""Write the Unicode 17.0 table functions of tokenize.pruv (between the BEGIN TABLES and END TABLES lines).

Each table is a binary search tree of `if c < X` tests over the code point segments of one value:
  wc(c)   0 not [\\p{L}\\p{N}], 1 a letter or number outside the four CJK scripts, 2 one inside them
  ct(c)   0 neither, 1 Cased and not Case_Ignorable, 2 Case_Ignorable (Final_Sigma context, ICU order)
  lw1(c)  the simple lowercase mapping; segments are a constant shift, or a shift on even offsets only
          (upper/lower pairs), identity elsewhere
Usage: gen_tokenize_tables.py [--check]
"""
import sys
from pathlib import Path

import tokenize_ucd

HERE = Path(__file__).resolve().parent
TARGET = HERE / 'tokenize.pruv'
TOP = 0x110000


def segments(f):
    out = []
    for c in range(TOP):
        v = f(c)
        if out and out[-1][2] == v:
            out[-1][1] = c
        else:
            out.append([c, c, v])
    return out


def lower_segments(lower1):
    """[(a, b, kind, d)]: kind 0 maps c to c + d, kind 1 maps c to c + d when (c - a) is even, else c."""
    shift = segments(lambda c: lower1.get(c, c) - c)
    out, k = [], 0
    while k < len(shift):
        a, b, d = shift[k]
        # pairs: one-point shift d, one-point identity, repeated
        j = k
        while (j + 1 < len(shift) and shift[j][0] == shift[j][1] and shift[j][2] == d and d != 0
               and shift[j + 1][0] == shift[j + 1][1] and shift[j + 1][2] == 0):
            j += 2
        if j - k >= 4:
            end = shift[j - 1][1]
            if j < len(shift) and shift[j][0] == shift[j][1] and shift[j][2] == d:
                end = shift[j][1]
                j += 1
            out.append((a, end, 1, d))
            k = j
            continue
        out.append((a, b, 0, d))
        k += 1
    return out


def tree(segs, leaf, depth):
    pad = '  ' * depth
    if len(segs) == 1:
        return leaf(segs[0], pad)
    mid = len(segs) // 2
    return '%sif c < %d {\n%s%s}\n%s' % (pad, segs[mid][0], tree(segs[:mid], leaf, depth + 1), pad,
                                        tree(segs[mid:], leaf, depth))


def small(seg, pad):
    return '%sreturn %d;\n' % (pad, seg[2])


def lower_leaf(seg, pad):
    a, _, kind, d = seg
    if d == 0:
        return '%sreturn c;\n' % pad
    if kind == 0:
        return '%sreturn c + %d;\n' % (pad, d) if d > 0 else '%sreturn c - %d;\n' % (pad, -d)
    sign = '+' if d > 0 else '-'
    return '%sif (c - %d) %% 2 == 0 { return c %s %d; }\n%sreturn c;\n' % (pad, a, sign, abs(d), pad)


def tables():
    d = tokenize_ucd.load()
    wc = segments(lambda c: 0 if c not in d['word'] else 2 if c in d['cjk'] else 1)
    ct = segments(lambda c: 2 if c in d['ignorable'] else 1 if c in d['cased'] else 0)
    lw = lower_segments(d['lower1'])
    check = {}  # the lower segments must give lower1 back
    for a, b, kind, dd in lw:
        for c in range(a, b + 1):
            check[c] = c + dd if kind == 0 or (c - a) % 2 == 0 else c
    assert all(check[c] == d['lower1'].get(c, c) for c in range(TOP))
    assert d['lower_full'] == {0x130: [0x69, 0x307]}
    head = ('// BEGIN TABLES (generated by gen_tokenize_tables.py from UCD 17.0.0: %d, %d and %d segments)\n'
            % (len(wc), len(ct), len(lw)))
    body = ('fn wc(c: i64) -> i64\n  ensures 0 <= result && result <= 2\n{\n' + tree(wc, small, 1) + '}\n\n'
            'fn ct(c: i64) -> i64\n  ensures 0 <= result && result <= 2\n{\n' + tree(ct, small, 1) + '}\n\n'
            'fn lw1(c: i64) -> i64 {\n' + tree(lw, lower_leaf, 1) + '}\n')
    return head + body + '// END TABLES\n'


def main():
    src = TARGET.read_text()
    a = src.index('// BEGIN TABLES')
    b = src.index('// END TABLES\n') + len('// END TABLES\n')
    new = src[:a] + tables() + src[b:]
    if '--check' in sys.argv:
        if new != src:
            print('tokenize.pruv tables are stale')
            return 1
        return 0
    TARGET.write_text(new)
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
