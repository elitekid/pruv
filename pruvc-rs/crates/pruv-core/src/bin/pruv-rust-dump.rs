//! Usage: pruv-rust-dump [--no-verify] [--trust-callers] [--budget N] FILE...
//! Writes exactly one line (UTF-8, ending with \n) per file to stdout, in order.
//! After parse+check (the verifier is not run), the gen_rust result is emitted as {"rs"}, and errors as {"error"|"internal"|"adapter_error"}.
//! Each line is flushed immediately: even if one file overflows the stack and aborts, the lines of earlier files remain.

use pruv_core::pyjson::{dumps_sorted, Json};
use std::io::Write;

struct Opts {
    verified: bool,
    trust_callers: bool,
    budget: u64,
    files: Vec<std::ffi::OsString>,
}

fn obj1(k: &str, v: Json) -> String {
    dumps_sorted(&Json::Obj(vec![(k.to_string(), v)]))
}

fn line_for(path: &std::ffi::OsStr, o: &Opts) -> String {
    // G4: through the module loader; G4 A2: an explicit-mode program is generated by the Rust backend (no guard, as the
    // adapter's gen_rust)
    let loaded = match pruv_core::modules::load_program(std::path::Path::new(path)) {
        Ok(l) => l,
        Err(pruv_core::modules::LoadError::Io(_)) => return obj1("adapter_error", Json::str("io")),
        Err(pruv_core::modules::LoadError::Decode(_)) => return obj1("adapter_error", Json::str("decode")),
        Err(pruv_core::modules::LoadError::Lang(e)) => return obj1("error", e.to_json_value()),
    };
    let mut prog = loaded.prog;
    let g4 = match loaded.g4 {
        Some(mut g) => {
            if let Err(e) = pruv_core::check::check_explicit(&mut prog, &mut g, &[]) {
                return obj1("error", e.to_json_value());
            }
            Some(g)
        }
        None => {
            if let Err(e) = pruv_core::check::check(&mut prog) {
                return obj1("error", e.to_json_value());
            }
            None
        }
    };
    // G9 A2: the Rust backend lowers G9 programs; no guard here (a runtime requires it cannot lower is a Diag below)
    // like Python gen_rust (default foreign checks, no externs; a G6 program is lowered, the manifest is not part of the
    // dump): a generic (or explicit-mode) program is specialized first (a specialization limit is a diagnostic)
    match pruv_core::codegen::gen_rust_any_g4(&prog, g4.as_ref(), o.verified, o.trust_callers, o.budget) {
        Ok(rs) => obj1("rs", Json::Str(rs)),
        Err(pruv_core::codegen::GenError::Diag(e)) => obj1("error", e.to_json_value()),
        Err(pruv_core::codegen::GenError::Msg(msg)) => obj1("internal", Json::Str(msg)),
    }
}

fn work(o: Opts) -> bool {
    let stdout = std::io::stdout();
    let mut lock = stdout.lock();
    for f in &o.files {
        let line = line_for(f, &o);
        if lock.write_all(line.as_bytes()).is_err() || lock.write_all(b"\n").is_err() || lock.flush().is_err() {
            return false;
        }
    }
    true
}

fn usage() -> ! {
    eprintln!("usage: pruv-rust-dump [--no-verify] [--trust-callers] [--budget N] FILE...");
    std::process::exit(2);
}

fn main() {
    let mut o = Opts { verified: true, trust_callers: false, budget: 1 << 30, files: Vec::new() };
    let mut it = std::env::args_os().skip(1);
    while let Some(a) = it.next() {
        match a.to_str() {
            Some("--no-verify") => o.verified = false,
            Some("--trust-callers") => o.trust_callers = true,
            Some("--budget") => match it.next().and_then(|v| v.to_str().and_then(|s| s.parse::<u64>().ok())) {
                Some(n) => o.budget = n,
                None => usage(),
            },
            _ => o.files.push(a),
        }
    }
    if o.files.is_empty() {
        usage();
    }
    // Run on a large-stack thread for deeply nested input.
    let handle = std::thread::Builder::new().stack_size(1 << 30).spawn(move || work(o));
    match handle.map(|h| h.join()) {
        Ok(Ok(true)) => {}
        _ => {
            eprintln!("pruv-rust-dump: internal failure");
            std::process::exit(1);
        }
    }
}
